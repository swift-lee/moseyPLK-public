def sha(p):
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def archive(path, files):
    with zipfile.ZipFile(path, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name, p in sorted(files):
            info = zipfile.ZipInfo(name, date_time=(2026, 9, 14, 0, 0, 0))
            mode = 0o755 if p.name.endswith('.sh') or p.name in ['mosey_launcher', 'mosey_server', 'update-binary'] else 0o644
            info.external_attr = (stat.S_IFREG | mode) << 16
            info.create_system = 3
            z.writestr(info, p.read_bytes(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)


def asset_path(path):
    """Restrict local inputs and generated output to the ignored work area."""
    path = Path(path).absolute()
    assets = ASSETS.absolute()
    try:
        relative = path.relative_to(assets)
    except ValueError as error:
        raise ValueError('Path must be inside moseyPLK-assets.') from error
    if not relative.parts or '..' in relative.parts:
        raise ValueError('An ordinary path inside moseyPLK-assets is required.')
    current = assets
    for part in ('', *relative.parts):
        if part:
            current /= part
        if current.is_symlink():
            raise ValueError('Symlinks are not allowed in local build input/output paths.')
    return path


def require_asset_file(path, description, expected_sha=None):
    try:
        path = asset_path(path)
    except ValueError as error:
        raise SystemExit(str(error)) from error
    if not path.is_file() or not stat.S_ISREG(path.stat().st_mode) or not path.stat().st_size:
        raise SystemExit(f'Missing or empty {description}: {path}; provide this local input explicitly.')
    if expected_sha is not None and sha(path) != expected_sha:
        raise SystemExit(f'Unexpected SHA-256 for {description}: {path}; the input was not overwritten.')
    return path


def validate_module_inputs():
    """Fail before compilation when restricted packaging inputs are unavailable."""
    compatibility = require_asset_file(
        ASSETS / 'build/generated/compatibility.sh', 'generated compatibility checks')
    try:
        text = compatibility.read_text()
    except (UnicodeError, OSError) as error:
        raise SystemExit('Generated compatibility checks must be readable shell text.') from error
    count = re.search(r"^    echo 'OK: ([1-9][0-9]*) reviewed Mosey prerequisites'$", text, re.M)
    calls = re.findall(r'^    mosey_require_(?:line|member) ', text, re.M)
    if ('# Generated by scripts/generate_compatibility.py.' not in text
            or 'mosey_check_compatibility() {' not in text or count is None
            or int(count.group(1)) != len(calls)):
        raise SystemExit('Generated compatibility checks are incomplete; run scripts/generate_compatibility.py.')
    inputs = {
        'compatibility.sh': compatibility,
        'sepolicy.rule': require_asset_file(
            ASSETS / 'restricted-inputs/sepolicy.rule', 'restricted SELinux policy', SEPOLICY_SHA),
        LAUNCHER: require_asset_file(
            ASSETS / 'research/module' / LAUNCHER, 'user-provided Fold6 launcher', LAUNCHER_SHA),
    }
    for relative, expected in DONOR.items():
        inputs['system/' + relative] = require_asset_file(
            ASSETS / 'research/extracted/OxygenOS' / relative,
            'user-provided donor ' + relative, expected)
    return inputs


def copy_public_tree(relative, destination, *, exclude=()):
    """Stage reviewed public files without recursively copying a working tree."""
    prefix = relative.rstrip('/') + '/'
    copied = 0
    for name, path in source_files(root=ROOT):
        if name.startswith(prefix):
            inside = name[len(prefix):]
            if inside in exclude:
                continue
            target = destination / inside
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            copied += 1
    if not copied:
        raise SystemExit('No reviewed public source files for ' + relative)


def stage_module_inputs(stage, inputs):
    for relative, path in inputs.items():
        target = stage / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)


